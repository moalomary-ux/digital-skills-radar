/** Resolve a technology's text fields for the active language (AR with EN fallback). */
export function localizeTech(
  tech: { id: string; trlRationale: string; employeeSkills: string[]; learningFocus: { awareness: string; practitioner: string } },
  lang: 'ar' | 'en'
): { rationale: string; skills: string[]; focus: { awareness: string; practitioner: string } } {
  if (lang === 'en') {
    return { rationale: tech.trlRationale, skills: tech.employeeSkills, focus: tech.learningFocus }
  }
  const ar = techAr[tech.id]
  if (!ar) return { rationale: tech.trlRationale, skills: tech.employeeSkills, focus: tech.learningFocus }
  return { rationale: ar.rationale, skills: ar.skills, focus: ar.focus }
}
